export type Locale = 'ar' | 'en' | 'ja';
export const LOCALES: Locale[] = ['ar', 'en', 'ja'];
export const DEFAULT_LOCALE: Locale = 'ar';

/** Every human-readable string is provided in all three locales. */
export interface Localized {
  ar: string;
  en: string;
  ja: string;
}

export type Cost = 1 | 2 | 3 | 4 | 5;
export type Tier = 'S' | 'A' | 'B' | 'C' | 'X';
export type Star = 1 | 2 | 3;
export type AugmentTierKey = 'silver' | 'gold' | 'prism';

export interface ChampionAbility {
  name: Localized;
  desc: Localized;
  variables: { name: string; value: number[] }[];
}

export interface ChampionStats {
  hp?: number;
  mana?: number;
  initialMana?: number;
  damage?: number;
  attackSpeed?: number;
  armor?: number;
  magicResist?: number;
  range?: number;
}

export interface Champion {
  id: string;
  name: Localized;
  cost: Cost;
  /** Stable trait apiNames (e.g. DA_18_Elderwood) — never localized names. */
  traits: string[];
  icon: string | null;
  ability: ChampionAbility;
  stats: ChampionStats;
  role: string;
}

export interface TraitEffect {
  minUnits: number | null;
  maxUnits: number | null;
  style: number;
  variables: Record<string, number>;
}

export interface Trait {
  id: string;
  name: Localized;
  desc: Localized;
  effects: TraitEffect[];
}

export interface Item {
  id: string;
  name: Localized;
  desc: Localized;
  icon: string | null;
  components: string[];
  effects: Record<string, number | null | undefined>;
  kind: 'component' | 'completed';
}

export interface Augment {
  id: string;
  name: Localized;
  desc: Localized;
  effects: Record<string, number | null | undefined>;
  icon: string | null;
}

export interface CompUnit {
  champion: string;
  items: string[];
  star: Star;
  /** 0 = back row, 3 = front row */
  row: number;
  /** 0..6 */
  col: number;
  /** True when this unit should receive items first (main carries / main tank). */
  itemPriority?: boolean;
}

export interface CompAugment {
  id: string;
  /** TFT Academy marks the stage (silver/gold/prism) when the guide specifies one. */
  tier?: AugmentTierKey;
  /** Short reason the augment fits this comp, when the guide provides one. */
  why?: Localized;
}

export interface LevelingStep {
  stage: Localized;
  text: Localized;
}

export interface CompAlternative {
  champion: string;
  /** Unit this one swaps out — optional when the guide only names the incoming unit. */
  replaces?: string;
  note: Localized;
}

/** Bench/early-game holders shown before the final board comes together. */
export interface CompEarlyUnit {
  champion: string;
  items: string[];
  star: Star;
}

/** Alternative (often artifact) item set for a unit already in the comp. */
export interface CompAltBuild {
  champion: string;
  items: string[];
}

export interface Comp {
  slug: string;
  name: Localized;
  subtitle: Localized;
  tier: Tier;
  difficulty: 1 | 2 | 3;
  playstyle: Localized;
  level: Localized;
  summary: Localized;
  units: CompUnit[];
  augments: CompAugment[];
  leveling: LevelingStep[];
  tips: Localized[];
  alternatives: CompAlternative[];
  /** Components worth grabbing from the carousel. */
  carousel?: string[];
  /** Early-game board before the comp is online. */
  early?: CompEarlyUnit[];
  /** Alternate item builds (e.g. artifact lines). */
  altBuilds?: CompAltBuild[];
  /** Recommended augment categories (economy, items, combat…). */
  augmentTypes?: Localized[];
  /** Original guide URL (imported comps keep their source). */
  source?: string;
}

/** Patch notes (generated by scripts/fetch_patch_notes.py from Riot's articles). */
export type PatchRefKind = 'champion' | 'trait' | 'item' | 'augment';
export type PatchGroupKind = PatchRefKind | 'system';
export type ChangeDirection = 'buff' | 'nerf' | 'adjust' | 'change';

export interface PatchEntry {
  /** Name as printed in the article — prefer the linked game object's name when ref is set. */
  name: Localized;
  /** Resolved against src/data when the article names a known champion/trait/item/augment. */
  ref: { k: PatchRefKind; id: string } | null;
  /** e.g. "Attack Speed: .7% ⇒ .75%" — direction is derived from these, locale-free. */
  lines: Localized[];
}

export interface PatchGroup {
  title: Localized;
  kind: PatchGroupKind;
  commentary: Localized | null;
  entries: PatchEntry[];
  notes: Localized[];
}

export interface PatchSection {
  id: string;
  title: Localized;
  commentary: Localized | null;
  groups: PatchGroup[];
}

export interface PatchInfo {
  slug: string;
  /** Human label, e.g. "18.4" or "18.4b". */
  label: string;
  /** ISO date, e.g. "2026-10-06". */
  date: string;
  title: Localized;
  desc: Localized;
  intro: Localized | null;
  designers: string[];
  /** Official article URL per locale. */
  urls: Record<Locale, string>;
  sections: PatchSection[];
}

export interface PatchNotesData {
  source: string;
  set: number;
  fetched: string;
  patches: PatchInfo[];
}
